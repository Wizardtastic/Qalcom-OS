-- rows of five cells ('#' on, '.' off). Rendering is decoupled from the canvas:
-- draw() takes a rect(px, py, w, h, color) callback, so a glyph pixel becomes a
-- scale x scale block. Lowercase renders as uppercase. Pure aside from the
