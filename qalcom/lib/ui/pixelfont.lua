function PixelFont.glyph(ch)
    return G[ch] or G[tostring(ch or ""):upper()] or G[" "]
end

function PixelFont.width(text, scale, spacing)
    scale = math.max(1, math.floor(tonumber(scale) or 1))
    spacing = math.floor(tonumber(spacing) or scale)
    text = tostring(text or "")
    if #text == 0 then return 0 end
    return #text * (PixelFont.cellW * scale) + (#text - 1) * spacing
end

function PixelFont.draw(rect, x, y, text, color, scale, spacing)
    -- rect(px, py, w, h, color) draws a filled block. Each on cell becomes a
    -- scale x scale block. Returns the x just past the drawn text.
    scale = math.max(1, math.floor(tonumber(scale) or 1))
    spacing = math.floor(tonumber(spacing) or scale)
    x = math.floor(x); y = math.floor(y)
    text = tostring(text or ""):upper()
    local advance = PixelFont.cellW * scale + spacing
    for index = 1, #text do
        local glyph = PixelFont.glyph(text:sub(index, index))
        local baseX = x + (index - 1) * advance
        for row = 1, PixelFont.cellH do
            local line = glyph[row]
            for col = 1, PixelFont.cellW do
                if line:sub(col, col) == "#" then
                    rect(baseX + (col - 1) * scale, y + (row - 1) * scale, scale, scale, color)
                end
            end
        end
    end
    return x + #text * advance - spacing
end

return PixelFont
